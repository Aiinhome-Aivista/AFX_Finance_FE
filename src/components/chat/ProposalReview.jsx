import { useEffect, useState } from 'react'
import { AlertTriangle, Check, GitPullRequest, X } from 'lucide-react'
import ConfirmDialog from '../common/ConfirmDialog'
import { Spinner } from '../common/States'

const OP = {
  add_node: ['New entity', 'bg-ok/15 text-ok'], update_node: ['Update', 'bg-warn/15 text-warn'], remove_node: ['Remove', 'bg-bad/15 text-bad'],
  add_edge: ['New link', 'bg-ok/15 text-ok'], remove_edge: ['Remove link', 'bg-bad/15 text-bad'], update_edge: ['Relabel', 'bg-warn/15 text-warn'],
}

/** Review a pending change proposal: approve/reject each change, or all at once. Nothing is applied before approval. */
export default function ProposalReview({ proposal, busy, onDecide, approveLabel = 'Approve & create new version' }) {
  const [checked, setChecked] = useState(new Set())
  const [confirm, setConfirm] = useState(null)
  useEffect(() => { setChecked(new Set(proposal?.items.map((i) => i.id))) }, [proposal?.id]) // eslint-disable-line react-hooks/exhaustive-deps
  if (!proposal) return null
  const pending = proposal.status === 'pending'
  const toggle = (id) => { const s = new Set(checked); s.has(id) ? s.delete(id) : s.add(id); setChecked(s) }
  return (
    <section className="card p-4" aria-label="Proposed changes">
      <div className="flex items-start gap-2"><GitPullRequest size={18} className="mt-0.5 text-brand" />
        <div className="min-w-0 flex-1"><h3 className="font-semibold">{proposal.title}</h3>
          {proposal.summary && <p className="mt-0.5 text-xs text-muted">{proposal.summary}</p>}
          <p className="mt-1 text-[11px] text-muted">Generated by {proposal.llm_used ? 'the configured LLM' : 'the rule-based engine'} · validated against your current graph · based on KG{proposal.base_version}</p></div>
        {!pending && <span className={`badge ${proposal.status === 'approved' ? 'bg-ok/15 text-ok' : 'bg-surface2 text-muted'}`}>{proposal.status}{proposal.result_version ? ` → KG${proposal.result_version}` : ''}</span>}
      </div>
      <ul className="mt-3 space-y-2">
        {proposal.items.map((i) => {
          const [label, cls] = OP[i.op] || [i.op, 'bg-surface2']
          return (
            <li key={i.id} className={`rounded-xl border p-3 ${pending && checked.has(i.id) ? 'border-brand/50' : 'border-line'} ${i.status === 'rejected' ? 'opacity-60' : ''}`}>
              <div className="flex items-start gap-3">
                {pending ? <input type="checkbox" className="mt-1 h-4 w-4 accent-[rgb(var(--brand))]" checked={checked.has(i.id)} onChange={() => toggle(i.id)} aria-label={`Approve: ${i.description}`} />
                  : i.status === 'approved' ? <Check size={16} className="mt-0.5 text-ok" /> : <X size={16} className="mt-0.5 text-muted" />}
                <div className="min-w-0 flex-1">
                  <span className={`badge ${cls}`}>{label}</span>
                  <p className="mt-1 text-sm">{i.description}</p>
                  {i.rationale && <p className="mt-0.5 text-xs text-muted">{i.rationale}</p>}
                  {i.warnings?.map((w, k) => <p key={k} className="mt-1 flex items-start gap-1 text-xs text-warn"><AlertTriangle size={12} className="mt-0.5 shrink-0" />{w}</p>)}
                </div>
              </div>
            </li>
          )
        })}
      </ul>
      {pending && (
        <div className="mt-4 flex flex-wrap gap-2">
          <button className="btn-primary" disabled={busy || checked.size === 0} onClick={() => onDecide('selected', [...checked])}>{busy && <Spinner />}{checked.size === proposal.items.length ? approveLabel : `Approve ${checked.size} selected`}</button>
          <button className="btn-ghost" disabled={busy} onClick={() => setConfirm('reject')}>Reject all</button>
        </div>
      )}
      <ConfirmDialog open={confirm === 'reject'} danger title="Reject all proposed changes?" confirmLabel="Reject all" busy={busy}
        onCancel={() => setConfirm(null)} onConfirm={async () => { await onDecide('reject_all'); setConfirm(null) }}>
        None of these changes will be added to your graph. You can ask the chatbot to propose again later.
      </ConfirmDialog>
    </section>
  )
}
